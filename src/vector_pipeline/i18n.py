TEXT = {"ru": _RUSSIAN, "en": {message: message for message in _RUSSIAN}}


def translate(message, language="ru", **values):
    """Translate presentation text only; unknown source values pass through unchanged."""
    template = TEXT.get(language, TEXT["ru"]).get(message, message)
    return template.format(**values) if values else template


def localize_frame(frame, language="ru"):
    """Translate known presentation columns, never identifiers or manager-entered text."""
    result = frame.copy()
    for column in ("Component", "Action", "Status", "Scenario", "Measure", "Workflow check", "Reason", "Model", "status"):
        if column in result:
            result[column] = result[column].map(lambda value: translate(value, language) if isinstance(value, str) else value)
    return result.rename(columns=lambda key: translate(key, language))


def error_text(error, language="ru"):
    message = str(error)
    if message in TEXT["en"]:
        return translate(message, language)
    for prefix in ("Acceptance report is stale:", "Integrity check failed:", "Row count mismatch:",
                   "Quantity is below the applied minimum of", "Quantity must be a multiple of the applied step"):
        if message.startswith(prefix):
            return translate(prefix, language) + " " + message[len(prefix):].strip()
    return message
